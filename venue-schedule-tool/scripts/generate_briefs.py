def _cell(value) -> str:
    """Markdown 表格单元格：转义竖线、压缩换行，避免撑破表格。"""
    if value is None:
        return ""
    if isinstance(value, (list, tuple)):
        value = "；".join(str(x) for x in value)
    return str(value).replace("|", "\\|").replace("\r", "").replace("\n", "<br>")


def md_table(headers, rows) -> str:
    """由表头与行数据生成 Markdown 表格。"""
    out = ["| " + " | ".join(_cell(h) for h in headers) + " |",
           "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        out.append("| " + " | ".join(_cell(c) for c in row) + " |")
    return "\n".join(out)


def md_head(title: str, note: str = "") -> str:
    """所有 Markdown 共用的抬头：标题 + 演练声明 + 元信息。"""
    lines = [f"# {title}", "", f"> **{META['演练声明']}**", "",
             f"- 项目：{META['项目']}",
             f"- 版本 / 日期：{META['文档版本']} / {META['编制日期']}",
             f"- 证据覆盖：{META['证据覆盖']}",
             f"- 生成方式：`scripts/generate_briefs.py`（单一数据源，重跑即可再生成）"]
    if note:
        lines.append(f"- 说明：{note}")
    lines.append("")
    return "\n".join(lines)


def fact_ids(text: str) -> list[str]:
    """从一段话里抽出引用到的事实编号（用于逐字稿溯源）。"""
    return list(dict.fromkeys(FACT_RE.findall(text or "")))


def emit(name: str, json_obj: dict, md_text: str, csv_headers: list[str], csv_rows: list[list]) -> None:
    """把一份说明文件同时写成 json / md / csv，并做基础自检。"""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / f"{name}.json").write_text(
        json.dumps(json_obj, ensure_ascii=False, indent=2), encoding="utf-8")
    (OUT_DIR / f"{name}.md").write_text(md_text.rstrip() + "\n", encoding="utf-8")
    with (OUT_DIR / f"{name}.csv").open("w", encoding="utf-8-sig", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(csv_headers)
        writer.writerows(csv_rows)
    assert META["演练声明"][:8] in md_text, f"{name}.md 缺少演练声明"
    assert all(len(r) == len(csv_headers) for r in csv_rows), f"{name}.csv 列数不一致"
    print(f"  {name}: json / md / csv（CSV {len(csv_rows)} 行）")


