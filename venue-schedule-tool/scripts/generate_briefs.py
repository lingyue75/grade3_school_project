def defaultdict_to_dict(records):
    """把扁平字段表按「分类」聚成对象，方便 JSON 消费方按章节读取。"""
    out = defaultdict(list)
    for r in records:
        out[r["分类"]].append({"字段": r["字段"], "内容": r["内容"],
                               "依据事实": r["依据事实"], "状态": r["状态"]})
    return dict(out)


