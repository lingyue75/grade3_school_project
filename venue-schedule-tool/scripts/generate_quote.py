COST_PER_MIN = 1.0      # 人力成本 1 元/分钟（= 60 元/小时，演练假设）
BASE_ORDERS = 45        # 月单量：取自演练样本，非统计台账
BASE_SAVED_MIN = 20     # 单均节省核对分钟（演练假设）
AMORT_YEARS = 3         # 摊销年限
ORDERS_SCENARIO = [30, 45, 60]
SAVED_SCENARIO = [10, 20, 35]


def annual_labor_saving(orders: int, saved_min: int, coverage: float) -> float:
    """年化工时节约 = 月单量 × 单均节省分钟 × 分钟成本 × 12 × 覆盖率。"""
    return orders * saved_min * COST_PER_MIN * 12 * coverage


